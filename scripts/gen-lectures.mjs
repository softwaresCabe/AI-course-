// Compiles src/content/weeks/wNN.md lecture notes into a typed TS module so any bundler
// (Next.js/Turbopack, Vite, Node scripts, a DB seed) can import them without special loaders.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(import.meta.dirname, '..', 'src', 'content', 'weeks');
const files = readdirSync(dir).filter((f) => /^w\d\d\.md$/.test(f)).sort();
const body = files.map((f) => `  ${f.replace('.md', '')}: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))},`).join('\n');
writeFileSync(
  join(dir, 'lectures.generated.ts'),
  `// AUTO-GENERATED by scripts/gen-lectures.mjs from wNN.md — edit the .md files, not this file.\nexport const lectures: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`lectures.generated.ts: ${files.length} lectures`);
